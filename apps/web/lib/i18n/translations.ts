export function translateUiText(lang: Language, source: string): string {
  if (lang === 'ar') return source
  const supplemental = UI_TEXT_TRANSLATIONS[source]
  if (supplemental) return supplemental[lang]
  const commonKey = ARABIC_KEYS.get(source)
  if (commonKey) return translations[lang][commonKey]
  return source.replace(UI_TOKEN_PATTERN, (_match, prefix: string, token: string) =>
    `${prefix}${UNIT_TRANSLATIONS[token]?.[lang] ?? token}`,
  )
}

/** Maps sidebar destination ids to translation keys. */
export const DESTINATION_KEYS: Record<string, TranslationKey> = {
  home: 'home',
  inventory: 'inventory',
  production: 'production',
  sales: 'sales',
  accounting: 'accounting',
  fleet: 'fleet',
  hr: 'hr',
  tasks: 'tasks',
  settings: 'settings',
}

export function destinationLabel(lang: Language, id: string, fallback: string): string {
  const key = DESTINATION_KEYS[id]
  return key ? t(lang, key) : fallback
}

export function t(lang: Language, key: TranslationKey): string {
  return translations[lang][key] || translations.en[key] || key
}

